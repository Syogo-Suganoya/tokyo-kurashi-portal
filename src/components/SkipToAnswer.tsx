/**
 * 「結果へ移動」リンク。
 *
 * どの画面も、見出しのあとに検索フォームが来る。キーボードで操作する人は、
 * 検索し直すたびにフォームの部品を全部たどらないと結果に着けない。
 * `/barrierfree` は条件のチェックボックスが8つ並ぶので、**10回以上Tabを押すことになる。**
 *
 * ふだんは見えず、Tabキーで当たったときだけ出てくる（`.skip-link`）。
 * 飛び先は結果を囲む要素で、`tabIndex={-1}` を付けて焦点を受け取れるようにしてある。
 * 付けないと画面がスクロールするだけで、次のTabがフォームの先頭に戻ってしまう。
 */
export function SkipToAnswer() {
  return (
    <a href="#answer" className="skip-link">
      結果へ移動
    </a>
  );
}
